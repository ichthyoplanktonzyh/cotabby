#!/usr/bin/env python3
"""Build blinded alignment review packets from an immutable experiment directory.

This offline boundary never contacts a model. It removes model/arm names and explanations,
deduplicates identical chunk outputs, and retains the private mapping for aggregation. Ratings
are independent reviewer judgements, not language benchmark ground truth. Strict parser failures
remain visible in structural metrics and are not silently repaired into semantic successes.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path


def write(path, data):
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n')


def reuse_ratings(directory, prior):
    """Reuse only exact normalized outputs under an identical corpus and unchanged rubric.

    This avoids paying review attention twice for the same evidence, regardless of model/arm.
    Other ratings already assigned in this run retain their reviewer rather than being replaced.
    """
    if json.loads((directory/'corpus.json').read_text()) != json.loads((prior/'corpus.json').read_text()):
        raise ValueError('Rating reuse requires an identical frozen corpus')
    rows=[json.loads(line) for line in (directory/'results.jsonl').read_text().splitlines()]
    ids=set()
    for row in rows:
        if row['formatValid']:
            key=json.dumps([row['caseID'],row['normalizedGroups']],ensure_ascii=False,sort_keys=True)
            ids.add('p_'+hashlib.sha256(key.encode()).hexdigest()[:16])
    review_dir=directory/'blind-review';review_dir.mkdir(exist_ok=True)
    other={r['id'] for path in review_dir.glob('ratings-*.json') if path.name!='ratings-reused.json'
           for r in json.loads(path.read_text())['ratings']}
    old={r['id']:r for path in (prior/'blind-review').glob('ratings-*.json') for r in json.loads(path.read_text())['ratings']}
    kept=[r for pid,r in old.items() if pid in ids and pid not in other]
    write(review_dir/'ratings-reused.json',{'reviewer':'Prior blinded ratings; identical corpus/output and rubric',
         'fromDirectory':str(prior),'ratings':kept})


def packets(directory, shard_count, batch):
    metadata = json.loads((directory/'metadata.json').read_text())
    rows = [json.loads(line) for line in (directory/'results.jsonl').read_text().splitlines()]
    corpus = {c['id']: c for c in json.loads((directory/'corpus.json').read_text())['cases']}
    unique = {}
    mapping = {}
    for row in rows:
        # Only strict-format outputs enter primary semantic review. Literal-invalid quotes still
        # enter: reviewers can identify incorrect or hallucinated alignment independently.
        if not row['formatValid']: continue
        key = json.dumps([row['caseID'], row['normalizedGroups']], ensure_ascii=False, sort_keys=True)
        opaque = 'p_' + hashlib.sha256(key.encode()).hexdigest()[:16]
        c = corpus[row['caseID']]
        unique[opaque] = {'id': opaque, 'sourceLanguage': c['sourceLanguage'],
            'targetLanguage': c['targetLanguage'], 'source': c['source'], 'translation': c['translation'],
            'meaningNotes': c['expectations'], 'groups': row['normalizedGroups']}
        mapping.setdefault(opaque, []).append(row['trialID'])
    review_dir = directory/'blind-review'
    review_dir.mkdir(exist_ok=True)
    rubric = {
        'alignment': '0: critical false correspondence; 1: material correction needed; 2: usable correspondence with at most minor imperfections. Rate all groups, not just one good pair.',
        'segmentation': '0: mechanically fragmented/unhelpful or long sentence as one group; 1: mixed usefulness or unnecessary large chunks; 2: coherent meaning chunks preserving phrases/constructions. Short greetings can be one chunk.',
        'coverage': '0: most important meaning missing; 1: material omissions; 2: important meaning covered. Ordinary punctuation and target-only grammatical articles need not be paired.',
        'scope': 'Judge ONLY chunk correspondence to the GIVEN fixed translation. Translation wording is not generated by this experiment. Discontinuous arrays and larger continuous constructions can both be valid. No exact gold segmentation.',
        'reviewer': 'Independent AI reviewer; flag language uncertainty. Do not infer model or arm. These are judgements, not certified accuracy.'}
    already_reviewed = set()
    for path in review_dir.glob('ratings-*.json'):
        already_reviewed.update(r['id'] for r in json.loads(path.read_text())['ratings'])
    ordered = sorted((item for pid, item in unique.items() if pid not in already_reviewed), key=lambda item: item['id'])
    for index in range(shard_count):
        write(review_dir/f'packet-{batch}-{index+1}.json', {'rubric': rubric, 'items': ordered[index::shard_count]})
    write(directory/'review-mapping-private.json', mapping)
    write(directory/'review-manifest.json', {'runStatus': metadata['status'], 'observedTrials': len(rows),
        'formatValidTrials': sum(r['formatValid'] for r in rows), 'uniqueReviewItems': len(unique), 'pendingReviewItems': len(ordered),
        'shards': shard_count, 'excluded': 'Strict format failures are excluded from primary semantic ratings, counted in protocol availability. No JSON repair.'})
    print('Review items', len(unique), 'from', len(rows), 'trials; run', metadata['status'])


def percentiles(values):
    ordered=sorted(values)
    def at(q):
        if not ordered: return None
        pos=(len(ordered)-1)*q; a=math.floor(pos); b=math.ceil(pos)
        return ordered[a]+(ordered[b]-ordered[a])*(pos-a)
    return {'n': len(ordered), 'p50': at(.5), 'p95': at(.95)}


def performance(rows):
    """Latency intersections keep before/after comparisons on identical successful fixtures.

    Failure latency is separately retained so a small success subset cannot conceal long tails.
    Repetitions are not independent language examples; no statistical significance is inferred.
    """
    groups={}
    paired={}
    for model in sorted({r['model'] for r in rows}):
        for arm in sorted({r['arm'] for r in rows if r['model']==model}):
            rs=[r for r in rows if r['model']==model and r['arm']==arm]
            groups[model+'-'+arm]={
                'allCompletionMs': percentiles([r['completionMs'] for r in rs]),
                'maxCompletionMs': max(r['completionMs'] for r in rs),
                'lengthLimitTrials': sum(r.get('finishReason')=='length' for r in rs),
                'singleGroupFormatValidTrials': sum(r['formatValid'] and len(r['normalizedGroups'])==1 for r in rs),
                'formatValidTrials': sum(r['formatValid'] for r in rs),
                'maxOutputBytes': max(len(r['rawOutput'].encode()) for r in rs),
                'fullyUniqueProtocolTrials': sum(r['protocolSucceeded'] and not r.get('multipleCandidateQuoteGroups',0) for r in rs)}
        for left,right in [('A','B'),('B','C'),('A','C'),('C','D'),('D','S'),('D','G'),('D','E'),('D','GE'),('S','G'),('S','E'),('G','GE'),('E','GE'),('GE','P'),('GE','R'),('P','R')]:
            if not all(any(r['model']==model and r['arm']==a for r in rows) for a in [left,right]): continue
            before={(r['caseID'],r.get('repetition',r.get('seed'))):r for r in rows if r['model']==model and r['arm']==left and r['protocolSucceeded']}
            after={(r['caseID'],r.get('repetition',r.get('seed'))):r for r in rows if r['model']==model and r['arm']==right and r['protocolSucceeded']}
            shared=before.keys() & after.keys()
            paired[model+'-'+left+'-to-'+right]={
                'completionRatio': percentiles([after[k]['completionMs']/before[k]['completionMs'] for k in shared]),
                'completionDifferenceMs': percentiles([after[k]['completionMs']-before[k]['completionMs'] for k in shared])}
    return {'arms': groups, 'pairedSuccessfulFixtures': paired}


def aggregate(directory):
    metadata = json.loads((directory/'metadata.json').read_text())
    if metadata['status'] != 'completed': raise ValueError('Only completed runs can be aggregated')
    rows = [json.loads(line) for line in (directory/'results.jsonl').read_text().splitlines()]
    mapping = json.loads((directory/'review-mapping-private.json').read_text())
    ratings = {}
    for path in sorted((directory/'blind-review').glob('ratings-*.json')):
        for rating in json.loads(path.read_text())['ratings']:
            pid = rating['id']
            if pid not in mapping or pid in ratings: raise ValueError('Unknown or duplicate review item: ' + pid)
            for dimension in ['alignment', 'segmentation', 'coverage']:
                if type(rating.get(dimension)) is not int or rating[dimension] not in range(3):
                    raise ValueError('Invalid rating: ' + pid)
            ratings[pid] = rating
    if set(ratings) != set(mapping): raise ValueError(f'Missing review ratings: {len(set(mapping)-set(ratings))}')
    by_trial = {trial: ratings[pid] for pid, trials in mapping.items() for trial in trials}
    result = {}
    for model in sorted({r['model'] for r in rows}):
        for arm in sorted({r['arm'] for r in rows if r['model']==model}):
            trials = [r for r in rows if r['model']==model and r['arm']==arm]
            scored = [by_trial[r['trialID']] for r in trials if r['trialID'] in by_trial]
            usable = [r for r in trials if r['protocolSucceeded'] and
                all(by_trial[r['trialID']][d]==2 for d in ['alignment','segmentation','coverage'])]
            result[model+'-'+arm] = {'trials': len(trials), 'semanticReviewed': len(scored),
                'allDimensions2': sum(all(s[d]==2 for d in ['alignment','segmentation','coverage']) for s in scored),
                'protocolAndAllDimensions2': len(usable),
                'scores': {d: {str(v): sum(s[d]==v for s in scored) for v in range(3)}
                           for d in ['alignment','segmentation','coverage']}}
    write(directory/'semantic-summary.json', result)
    write(directory/'performance-details.json', performance(rows))
    print(json.dumps(result, ensure_ascii=False, indent=2))


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['packets','aggregate'])
    parser.add_argument('directory', type=Path)
    parser.add_argument('--shards', type=int, default=3)
    parser.add_argument('--batch', default='final')
    parser.add_argument('--reuse-from',type=Path)
    args=parser.parse_args()
    if args.command=='packets':
        if args.shards < 1: raise ValueError('Positive shard count required')
        if args.reuse_from: reuse_ratings(args.directory,args.reuse_from)
        packets(args.directory, args.shards, args.batch)
    else: aggregate(args.directory)


if __name__=='__main__': main()
